-- Create ATTENDANCE_STATUS Table
CREATE TABLE ATTENDANCE_STATUS (
    STATUS_CODE VARCHAR2(20) PRIMARY KEY,
    DESCRIPTION VARCHAR2(100) NOT NULL
);

