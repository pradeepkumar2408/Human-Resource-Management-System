-- Create ATTENDANCE Table
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID NUMBER(19,0) PRIMARY KEY,
    EMPLOYEE_ID NUMBER(19,0) NOT NULL,
    DEPARTMENT_ID NUMBER(19,0),
    WORK_DATE DATE NOT NULL,
    CHECK_IN TIMESTAMP,
    CHECK_OUT TIMESTAMP,
    STATUS_CODE VARCHAR2(20) NOT NULL,
    AUDIT_REMARK VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ATT_STATUS FOREIGN KEY (STATUS_CODE) REFERENCES ATTENDANCE_STATUS(STATUS_CODE)
);

-- Create Sequence
CREATE SEQUENCE ATTENDANCE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
